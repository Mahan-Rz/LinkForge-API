from django.http import HttpResponse, HttpResponseRedirect
from rest_framework import serializers as drf_serializers
from rest_framework import generics
from rest_framework.authentication import TokenAuthentication
from rest_framework.authtoken.views import ObtainAuthToken
from rest_framework.filters import OrderingFilter, SearchFilter
from rest_framework.decorators import (
    api_view,
    authentication_classes,
    permission_classes,
)
from rest_framework.permissions import AllowAny, IsAuthenticated
from rest_framework.pagination import PageNumberPagination
from drf_spectacular.utils import (
    OpenApiParameter,
    OpenApiResponse,
    OpenApiTypes,
    extend_schema,
    extend_schema_view,
)

from .services import get_redirect_target, invalidate_redirect_cache
from .models import ShortenedURL
from .serializers import ShortenedURLSerializer


class TokenRequestSerializer(drf_serializers.Serializer):
    username = drf_serializers.CharField()
    password = drf_serializers.CharField(write_only=True)


class TokenResponseSerializer(drf_serializers.Serializer):
    token = drf_serializers.CharField()


class DocumentedObtainAuthToken(ObtainAuthToken):
    @extend_schema(
        summary='Obtain an API token',
        description='Exchange a Django username and password for an API token.',
        auth=[],
        request=TokenRequestSerializer,
        responses={
            200: TokenResponseSerializer,
            400: OpenApiResponse(description='Invalid credentials or request body.'),
        },
    )
    def post(self, request, *args, **kwargs):
        return super().post(request, *args, **kwargs)


class ShortenedURLPagination(PageNumberPagination):
    page_size = 10
    page_size_query_param = 'page_size'
    max_page_size = 100


@extend_schema_view(
    get=extend_schema(
        summary='List your shortened URLs',
        description=(
            'Returns only URLs owned by the authenticated user. Supports '
            'pagination, substring search on original_url, and ordering by '
            'created_at or click_count.'
        ),
        responses={
            200: ShortenedURLSerializer(many=True),
            401: OpenApiResponse(description='Authentication required.'),
        },
    ),
    post=extend_schema(
        summary='Create a shortened URL',
        description=(
            'Creates a URL for the authenticated user. The short code is '
            'generated by the server; owner and analytics fields are read-only. '
            'expires_at may be omitted or set to a future timestamp.'
        ),
        request=ShortenedURLSerializer,
        responses={
            201: ShortenedURLSerializer,
            400: OpenApiResponse(description='Invalid URL or expiry value.'),
            401: OpenApiResponse(description='Authentication required.'),
        },
    ),
)
class ShortenedURLListCreateView(generics.ListCreateAPIView):
    authentication_classes = [TokenAuthentication]
    permission_classes = [IsAuthenticated]
    queryset = ShortenedURL.objects.all()
    serializer_class = ShortenedURLSerializer
    pagination_class = ShortenedURLPagination
    filter_backends = [SearchFilter, OrderingFilter]
    search_fields = ['original_url']
    ordering_fields = ['created_at', 'click_count']
    ordering = ['-created_at']
    http_method_names = ['get', 'post', 'head', 'options']

    def get_queryset(self):
        return self.queryset.filter(owner=self.request.user)

    def perform_create(self, serializer):
        serializer.save(owner=self.request.user)


@extend_schema_view(
    get=extend_schema(
        summary='Retrieve one of your shortened URLs',
        responses={
            200: ShortenedURLSerializer,
            401: OpenApiResponse(description='Authentication required.'),
            404: OpenApiResponse(description='URL not found for this user.'),
        },
    ),
    put=extend_schema(
        summary='Replace a shortened URL destination and settings',
        description=(
            'Updates an owned URL. The generated code, owner, and analytics '
            'fields cannot be changed.'
        ),
        request=ShortenedURLSerializer,
        responses={
            200: ShortenedURLSerializer,
            400: OpenApiResponse(description='Invalid URL or expiry value.'),
            401: OpenApiResponse(description='Authentication required.'),
            404: OpenApiResponse(description='URL not found for this user.'),
        },
    ),
    delete=extend_schema(
        summary='Delete one of your shortened URLs',
        responses={
            204: OpenApiResponse(description='URL deleted.'),
            401: OpenApiResponse(description='Authentication required.'),
            404: OpenApiResponse(description='URL not found for this user.'),
        },
    ),
)
class ShortenedURLDetailView(generics.RetrieveUpdateDestroyAPIView):
    authentication_classes = [TokenAuthentication]
    permission_classes = [IsAuthenticated]
    queryset = ShortenedURL.objects.all()
    serializer_class = ShortenedURLSerializer
    http_method_names = ['get', 'put', 'delete', 'head', 'options']

    def get_queryset(self):
        return self.queryset.filter(owner=self.request.user)

    def perform_update(self, serializer):
        shortened_code = serializer.instance.shortened_code
        serializer.save()
        invalidate_redirect_cache(shortened_code)

    def perform_destroy(self, instance):
        invalidate_redirect_cache(instance.shortened_code)
        instance.delete()


@extend_schema(
    summary='Redirect through a shortened URL',
    description=(
        'Public endpoint. Active, unexpired URLs return a temporary redirect '
        'to the original URL and record a click. Unknown codes return 404; '
        'inactive or expired URLs return 410 Gone.'
    ),
    parameters=[
        OpenApiParameter(
            name='shortened_code',
            type=OpenApiTypes.STR,
            location=OpenApiParameter.PATH,
            description='The generated short code.',
        ),
    ],
    responses={
        302: OpenApiResponse(description='Temporary redirect to original_url.'),
        404: OpenApiResponse(description='Shortened code does not exist.'),
        410: OpenApiResponse(description='URL is inactive or expired.'),
    },
)
@api_view(['GET'])
@authentication_classes([])
@permission_classes([AllowAny])
def redirect_shortened_url(request, shortened_code):
    original_url = get_redirect_target(shortened_code)
    if original_url is None:
        return HttpResponse(status=410)
    return HttpResponseRedirect(original_url)
